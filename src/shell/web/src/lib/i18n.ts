const dictionaries: Record<Locale, Record<string, string>> = { 'zh-CN': zh, en };

export const languageOptions: { value: LanguageSetting; labelKey: string }[] = [
  { value: 'auto', labelKey: 'settings.languageAuto' },
  { value: 'zh-CN', labelKey: 'settings.languageZh' },
  { value: 'en', labelKey: 'settings.languageEn' },
];

function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, key: string) => {
    const value = vars[key];
    return value === undefined ? match : String(value);
  });
}

export function resolveLocale(setting: LanguageSetting): Locale {
  if (setting === 'zh-CN' || setting === 'en') {
    return setting;
  }
  const language =
    typeof navigator !== 'undefined' && navigator.language ? navigator.language : 'zh-CN';
  return language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export const locale = writable<Locale>('zh-CN');

export function applyLocale(setting: LanguageSetting): Locale {
  const next = resolveLocale(setting);
  locale.set(next);
  if (typeof document !== 'undefined') {
    document.documentElement.lang = next;
  }
  return next;
}

export const t = derived(locale, ($locale) => {
  return (key: string, vars?: Record<string, string | number>): string => {
    const template = dictionaries[$locale][key] ?? dictionaries['zh-CN'][key] ?? key;
    return format(template, vars);
  };
});

// For event handlers and menu construction where a store subscription is not
// convenient. Components still subscribe through $t for reactive rendering.
export function trNow(key: string, vars?: Record<string, string | number>): string {
  const current = get(locale);
  const template = dictionaries[current][key] ?? dictionaries['zh-CN'][key] ?? key;
  return format(template, vars);
}
